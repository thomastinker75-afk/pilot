import assert from 'node:assert/strict';
import { APPS, GLOSSARY, AGE_BANDS, CHECKLISTS } from '../src/content/data.ts';
import { APP_AUDITS } from '../src/content/apps-audit.ts';
import { explainMessage } from '../src/lib/slang-explainer.ts';
const app=slug=>APPS.find(a=>a.slug===slug);
assert.match(app('yubo').officialMinAge,/18/);
assert.match(app('telegram')?.officialMinAge??'',/18/);
assert.match(app('ngl-sendit').officialMinAge,/NGL: 18; Sendit: 13/);
assert.equal(GLOSSARY.find(g=>g.term==='1437').matchable,false);
assert.equal(explainMessage('1437').length,0);
assert.ok(!JSON.stringify(APPS).includes('A VPN defeats the whole thing'));
assert.equal(APPS.length,22);
assert.equal(new Set(APPS.map(a=>a.slug)).size,22);
for(const a of APPS) assert.ok(APP_AUDITS[a.slug],`Missing audit: ${a.slug}`);
assert.equal(AGE_BANDS.length,6);
assert.equal(CHECKLISTS.length,4);
assert.deepEqual(GLOSSARY.filter(g=>g.matchable===false).map(g=>g.term).sort(),['1437','212','Mango mustard','Snaked'].sort());
assert.equal(explainMessage('snaked').length,0);
const check=slug=>CHECKLISTS.find(c=>c.slug===slug);
assert.match(check('iphone-first-setup').emergency,/Show When Locked/);
assert.match(check('android-first-setup').emergency,/never make a test call/);
assert.ok(!JSON.stringify(CHECKLISTS).includes('Emergency calls always work'));
assert.ok(!JSON.stringify(CHECKLISTS).includes('£0.30'));
assert.match(JSON.stringify(check('youtube-safer')),/Shorts feed limit/);
assert.match(JSON.stringify(check('youtube-safer')),/dismissed or ignored/);
assert.ok(!JSON.stringify(check('youtube-safer')).includes('there is no switch'));
assert.match(JSON.stringify(AGE_BANDS.find(a=>a.slug==='14-15').screenTime),/frequency/i);
console.log('PASS: 22 app routes preserved, age distinctions, uncertain terms, study interpretation and parental-control limitations.');
